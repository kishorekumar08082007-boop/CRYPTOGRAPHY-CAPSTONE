"""
setup_db.py — Run this script ONCE to initialize the database, generate
the Fernet encryption key, and create the .env file automatically.

Usage:
    py setup_db.py
"""

import os
import sys
import getpass
import mysql.connector
from cryptography.fernet import Fernet


DOTENV_PATH = os.path.join(os.path.dirname(__file__), '.env')
SCHEMA_PATH = os.path.join(os.path.dirname(__file__), 'database', 'schema.sql')


def main():
    print("=" * 60)
    print("  Digital Signature System — Database Setup")
    print("=" * 60)

    # ── Collect MySQL credentials ────────────────────────────────
    print("\n[1] MySQL Connection Details")
    db_host = input("   MySQL host [localhost]: ").strip() or "localhost"
    db_port = input("   MySQL port [3306]: ").strip() or "3306"
    db_user = input("   MySQL username [root]: ").strip() or "root"
    db_password = getpass.getpass("   MySQL password: ")

    # ── Test connection ──────────────────────────────────────────
    print("\n[2] Testing MySQL connection...")
    try:
        conn = mysql.connector.connect(
            host=db_host,
            port=int(db_port),
            user=db_user,
            password=db_password,
            charset='utf8mb4'
        )
        conn.close()
        print("   ✓ Connection successful.")
    except mysql.connector.Error as e:
        print(f"   ✗ Connection failed: {e}")
        print("   Please check your MySQL credentials and try again.")
        sys.exit(1)

    # ── Run schema SQL ───────────────────────────────────────────
    print("\n[3] Creating database and tables...")
    try:
        conn = mysql.connector.connect(
            host=db_host,
            port=int(db_port),
            user=db_user,
            password=db_password,
            charset='utf8mb4',
            autocommit=True
        )
        cursor = conn.cursor()
        with open(SCHEMA_PATH, 'r') as f:
            schema = f.read()
        for stmt in schema.split(';'):
            stmt = stmt.strip()
            if stmt:
                try:
                    cursor.execute(stmt)
                except mysql.connector.Error as e:
                    if e.errno in (1050, 1007):  # table/db already exists
                        pass
                    else:
                        print(f"   Warning: {e}")
        cursor.close()
        conn.close()
        print("   ✓ Database 'digital_signature_system' and all tables created.")
    except Exception as e:
        print(f"   ✗ Schema setup failed: {e}")
        sys.exit(1)

    # ── Generate encryption key ──────────────────────────────────
    print("\n[4] Generating Fernet encryption key for private key storage...")
    fernet_key = Fernet.generate_key().decode()
    print("   ✓ Encryption key generated.")

    # ── Generate Flask secret key ────────────────────────────────
    flask_secret = os.urandom(32).hex()

    # ── Admin credentials ────────────────────────────────────────
    print("\n[5] Admin Account Setup")
    admin_email = input("   Admin email [admin@localdemo.test]: ").strip() or "admin@localdemo.test"
    admin_password = getpass.getpass("   Admin password [Admin@123]: ") or "Admin@123"

    # ── Write .env file ──────────────────────────────────────────
    print("\n[6] Writing .env configuration file...")
    env_content = f"""# Digital Signature System — Environment Configuration
# Generated by setup_db.py — Keep this file SECRET, never commit to git.

# Flask
FLASK_SECRET_KEY={flask_secret}
FLASK_DEBUG=True

# Database
DB_HOST={db_host}
DB_PORT={db_port}
DB_USER={db_user}
DB_PASSWORD={db_password}
DB_NAME=digital_signature_system

# Private Key Encryption (Fernet)
PRIVATE_KEY_ENCRYPTION_KEY={fernet_key}

# File Upload
MAX_CONTENT_LENGTH=16777216
UPLOAD_FOLDER=uploads
CERTIFICATES_FOLDER=certificates
KEYS_FOLDER=keys

# Admin Account
ADMIN_EMAIL={admin_email}
ADMIN_PASSWORD={admin_password}
"""
    with open(DOTENV_PATH, 'w') as f:
        f.write(env_content)
    print(f"   ✓ .env file written to: {DOTENV_PATH}")

    # ── Done ─────────────────────────────────────────────────────
    print("\n" + "=" * 60)
    print("  Setup complete!")
    print("=" * 60)
    print(f"\n  Admin email:    {admin_email}")
    print(f"  Admin password: {admin_password}")
    print("\n  To start the application:")
    print("    py app.py")
    print("\n  Then open: http://localhost:5000")
    print()


if __name__ == '__main__':
    main()
